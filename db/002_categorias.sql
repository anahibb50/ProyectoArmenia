-- 002 | PostgreSQL 14+ | Correr después del script base de ldbla.
-- No borra la temporada ni los horarios. Agrega el catálogo de categorías
-- y pasa la clave de equipos y partidos de serie A/B a categoria_id.
-- La serie queda solo en categorias (A o B en sénior; NULL en infantil y femenino).
-- La columna serie de equipos y partidos se conserva nullable para las vistas
-- que todavía la leen; ya no forma parte de la clave.

BEGIN;

SET search_path TO ldbla;

INSERT INTO temporadas (nombre)
VALUES ('2026-2027')
ON CONFLICT (nombre) DO NOTHING;

CREATE TABLE IF NOT EXISTS categorias (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temporada_id BIGINT NOT NULL,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(80) NOT NULL,
    disciplina VARCHAR(20) NOT NULL,
    serie CHAR(1) NULL,
    cupo_equipos SMALLINT NULL,
    puntos_victoria SMALLINT NOT NULL DEFAULT 3,
    puntos_empate SMALLINT NOT NULL DEFAULT 1,
    puntos_derrota SMALLINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_categorias_temporada FOREIGN KEY (temporada_id) REFERENCES temporadas (id),
    CONSTRAINT uq_categorias_codigo UNIQUE (temporada_id, codigo),
    CONSTRAINT uq_categorias_id_temporada UNIQUE (id, temporada_id),
    CONSTRAINT ck_categorias_disciplina CHECK (disciplina IN ('SENIOR', 'INFANTIL', 'FEMENINO')),
    CONSTRAINT ck_categorias_serie CHECK (serie IS NULL OR serie IN ('A', 'B')),
    CONSTRAINT ck_categorias_serie_disciplina CHECK (
        (disciplina = 'SENIOR' AND serie IN ('A', 'B'))
        OR (disciplina IN ('INFANTIL', 'FEMENINO') AND serie IS NULL)
    ),
    CONSTRAINT ck_categorias_cupo CHECK (cupo_equipos IS NULL OR cupo_equipos > 0),
    CONSTRAINT ck_categorias_puntos CHECK (
        puntos_victoria >= puntos_empate AND puntos_empate >= puntos_derrota
    )
);

CREATE TABLE IF NOT EXISTS etapas_categoria (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id SMALLINT NOT NULL,
    numero SMALLINT NOT NULL,
    nombre VARCHAR(40) NOT NULL,
    formato VARCHAR(30) NOT NULL,
    CONSTRAINT fk_etapas_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id),
    CONSTRAINT uq_etapas_categoria UNIQUE (categoria_id, numero),
    CONSTRAINT ck_etapas_numero CHECK (numero BETWEEN 1 AND 3),
    CONSTRAINT ck_etapas_formato CHECK (formato IN ('TODOS_CONTRA_TODOS', 'CUADRANGULARES', 'ELIMINACION'))
);

INSERT INTO categorias (
    temporada_id, codigo, nombre, disciplina, serie, cupo_equipos,
    puntos_victoria, puntos_empate, puntos_derrota
)
SELECT t.id, v.codigo, v.nombre, v.disciplina, v.serie, v.cupo, 3, 1, 0
FROM temporadas t
CROSS JOIN (
    VALUES
        ('SENIOR_A', 'Sénior A', 'SENIOR', CAST('A' AS CHAR(1)), CAST(12 AS SMALLINT)),
        ('SENIOR_B', 'Sénior B', 'SENIOR', CAST('B' AS CHAR(1)), CAST(14 AS SMALLINT)),
        ('INFANTIL', 'Infantil', 'INFANTIL', CAST(NULL AS CHAR(1)), CAST(NULL AS SMALLINT)),
        ('FEMENINO', 'Femenino', 'FEMENINO', CAST(NULL AS CHAR(1)), CAST(NULL AS SMALLINT))
) AS v(codigo, nombre, disciplina, serie, cupo)
WHERE t.nombre = '2026-2027'
ON CONFLICT (temporada_id, codigo) DO NOTHING;

INSERT INTO etapas_categoria (categoria_id, numero, nombre, formato)
SELECT c.id, e.numero, e.nombre, e.formato
FROM categorias c
JOIN temporadas t ON t.id = c.temporada_id
JOIN (
    VALUES
        ('SENIOR_A', CAST(1 AS SMALLINT), 'Etapa 1', 'TODOS_CONTRA_TODOS'),
        ('SENIOR_A', CAST(2 AS SMALLINT), 'Etapa 2', 'TODOS_CONTRA_TODOS'),
        ('SENIOR_A', CAST(3 AS SMALLINT), 'Etapa 3', 'CUADRANGULARES'),
        ('SENIOR_B', CAST(1 AS SMALLINT), 'Etapa 1', 'TODOS_CONTRA_TODOS'),
        ('SENIOR_B', CAST(2 AS SMALLINT), 'Etapa 2', 'TODOS_CONTRA_TODOS')
) AS e(codigo, numero, nombre, formato) ON e.codigo = c.codigo
WHERE t.nombre = '2026-2027'
ON CONFLICT (categoria_id, numero) DO NOTHING;

ALTER TABLE equipos ADD COLUMN IF NOT EXISTS categoria_id SMALLINT;
ALTER TABLE partidos ADD COLUMN IF NOT EXISTS categoria_id SMALLINT;

UPDATE equipos e
SET categoria_id = c.id
FROM categorias c
WHERE e.categoria_id IS NULL
  AND e.temporada_id = c.temporada_id
  AND (
      (e.serie = 'A' AND c.codigo = 'SENIOR_A')
      OR (e.serie = 'B' AND c.codigo = 'SENIOR_B')
  );

UPDATE partidos p
SET categoria_id = c.id
FROM categorias c
WHERE p.categoria_id IS NULL
  AND p.temporada_id = c.temporada_id
  AND (
      (p.serie = 'A' AND c.codigo = 'SENIOR_A')
      OR (p.serie = 'B' AND c.codigo = 'SENIOR_B')
  );

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM equipos WHERE categoria_id IS NULL) THEN
        RAISE EXCEPTION 'Hay equipos sin categoría. Solo se migran series A y B hacia Sénior A y Sénior B.';
    END IF;

    IF EXISTS (SELECT 1 FROM partidos WHERE categoria_id IS NULL) THEN
        RAISE EXCEPTION 'Hay partidos sin categoría. Solo se migran series A y B hacia Sénior A y Sénior B.';
    END IF;
END $$;

ALTER TABLE equipos ALTER COLUMN categoria_id SET NOT NULL;
ALTER TABLE partidos ALTER COLUMN categoria_id SET NOT NULL;

ALTER TABLE partidos DROP CONSTRAINT IF EXISTS fk_partidos_local;
ALTER TABLE partidos DROP CONSTRAINT IF EXISTS fk_partidos_visitante;
ALTER TABLE equipos DROP CONSTRAINT IF EXISTS fk_equipos_categoria;
ALTER TABLE equipos DROP CONSTRAINT IF EXISTS fk_equipos_categoria_temporada;
ALTER TABLE partidos DROP CONSTRAINT IF EXISTS fk_partidos_categoria;
ALTER TABLE partidos DROP CONSTRAINT IF EXISTS fk_partidos_categoria_temporada;

ALTER TABLE equipos DROP CONSTRAINT IF EXISTS uq_equipos_clave_compuesta;
ALTER TABLE equipos DROP CONSTRAINT IF EXISTS uq_equipos_nombre;
ALTER TABLE equipos DROP CONSTRAINT IF EXISTS uq_equipos_nombre_categoria;
ALTER TABLE equipos DROP CONSTRAINT IF EXISTS ck_equipos_serie;
ALTER TABLE partidos DROP CONSTRAINT IF EXISTS ck_partidos_serie;

ALTER TABLE equipos ALTER COLUMN serie DROP NOT NULL;
ALTER TABLE partidos ALTER COLUMN serie DROP NOT NULL;

ALTER TABLE equipos
    ADD CONSTRAINT uq_equipos_clave_compuesta UNIQUE (id, temporada_id, categoria_id);

ALTER TABLE equipos
    ADD CONSTRAINT uq_equipos_nombre_categoria UNIQUE (temporada_id, categoria_id, nombre);

ALTER TABLE equipos
    ADD CONSTRAINT fk_equipos_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id);

ALTER TABLE equipos
    ADD CONSTRAINT fk_equipos_categoria_temporada
    FOREIGN KEY (categoria_id, temporada_id) REFERENCES categorias (id, temporada_id);

ALTER TABLE partidos
    ADD CONSTRAINT fk_partidos_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id);

ALTER TABLE partidos
    ADD CONSTRAINT fk_partidos_categoria_temporada
    FOREIGN KEY (categoria_id, temporada_id) REFERENCES categorias (id, temporada_id);

ALTER TABLE partidos
    ADD CONSTRAINT fk_partidos_local
    FOREIGN KEY (equipo_local_id, temporada_id, categoria_id)
    REFERENCES equipos (id, temporada_id, categoria_id);

ALTER TABLE partidos
    ADD CONSTRAINT fk_partidos_visitante
    FOREIGN KEY (equipo_visitante_id, temporada_id, categoria_id)
    REFERENCES equipos (id, temporada_id, categoria_id);

CREATE INDEX IF NOT EXISTS ix_equipos_categoria ON equipos (categoria_id);
CREATE INDEX IF NOT EXISTS ix_partidos_categoria ON partidos (categoria_id);

DROP VIEW IF EXISTS vw_tabla_posiciones;

CREATE VIEW vw_tabla_posiciones AS
SELECT x.temporada_id,
       c.serie,
       x.etapa,
       x.fase,
       x.grupo_fase,
       x.equipo_id,
       e.nombre AS equipo,
       COUNT(*) AS pj,
       SUM(CASE WHEN x.gf > x.gc THEN 1 ELSE 0 END) AS pg,
       SUM(CASE WHEN x.gf = x.gc THEN 1 ELSE 0 END) AS pe,
       SUM(CASE WHEN x.gf < x.gc THEN 1 ELSE 0 END) AS pp,
       SUM(x.gf) AS gf,
       SUM(x.gc) AS gc,
       SUM(x.gf - x.gc) AS dg,
       SUM(CASE
           WHEN x.gf > x.gc THEN c.puntos_victoria
           WHEN x.gf = x.gc THEN c.puntos_empate
           ELSE c.puntos_derrota
       END) AS pts,
       x.categoria_id,
       c.codigo AS categoria
FROM (
    SELECT temporada_id, categoria_id, etapa, fase, grupo_fase,
           equipo_local_id AS equipo_id,
           goles_local_oficial AS gf, goles_visitante_oficial AS gc
    FROM partidos
    WHERE estado = 'APROBADO'
    UNION ALL
    SELECT temporada_id, categoria_id, etapa, fase, grupo_fase,
           equipo_visitante_id AS equipo_id,
           goles_visitante_oficial AS gf, goles_local_oficial AS gc
    FROM partidos
    WHERE estado = 'APROBADO'
) x
JOIN equipos e ON e.id = x.equipo_id
JOIN categorias c ON c.id = x.categoria_id
GROUP BY x.temporada_id, c.serie, x.etapa, x.fase, x.grupo_fase, x.equipo_id, e.nombre,
         x.categoria_id, c.codigo, c.puntos_victoria, c.puntos_empate, c.puntos_derrota;

COMMIT;
